std::expected<ProtoFiles, std::vector<Diagnostic>> emitProto(CheckedProgram& checked,
                                                             std::string_view stem) {
    std::vector<Diagnostic> faults;
    ProtoFiles files;
    files.proto = ProtoEmitter{checked, faults, stem}.emit();
    // The wrappers walk the same surface, so a source the proto refuses
    // would only say every refusal twice
    if (!faults.empty()) {
        return std::unexpected(std::move(faults));
    }
    const EmitLookup lookup{checked, faults};
    files.goSession = emitGoSession(lookup, stem);
    files.tsSession = emitTsSession(lookup, stem);
    return files;
}

