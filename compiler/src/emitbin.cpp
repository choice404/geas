// The standalone half of geas build --bin: the entry point rule over the
// checked tables, and the small C main() that turns the module into a
// program. The wrapper brings the runtime up, registers the module
// directly, freezes, signs Main, builds argv[1..] into a List<String> on
// the signed instance, fulfills run synchronously, and maps the outcome
// onto the process: Ok(n) exits with n's low eight bits, Err renders its
// payload to stderr and exits 1, and a fulfillment status other than
// GEAS_OK is a rendered diagnostic and exit 1 as well. The wrapper text is
// deterministic for a given root file, so it diffs like the module C
#include <algorithm>

#include "codegen.hpp"
#include "emitlookup.hpp"
#include "emittext.hpp"

namespace geas {

namespace {

constexpr std::string_view mainContractName = "Main";
constexpr std::string_view runPledgeName = "run";

// The wrapper, @STEM@ standing where the program's name goes
constexpr std::string_view wrapperTemplate =
    R"WRAP(/* generated by geas build --bin, do not edit: the Main entry wrapper. */
#include <geas/geas.h>

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* The module is linked into this executable, so its registrar is a plain
 * undefined reference here, no dlopen required. */
GeasStatus geas_module_register(GeasRuntime* rt);

static const char* k_prog = "@STEM@";

/* Renders v in its debug spelling and prints it to stderr: one sizing
 * pass, one malloc, one write pass, the geas_value_render protocol. */
static void render_stderr(const GeasValue* v) {
    size_t need = 0;
    geas_value_render(v, NULL, 0, &need); /* the sizing call */
    if (need == 0) {
        fputs("<unrenderable>", stderr);
        return;
    }
    char* buf = (char*)malloc(need);
    if (!buf) {
        fputs("<out of memory>", stderr);
        return;
    }
    if (geas_value_render(v, buf, need, &need) == GEAS_OK) fputs(buf, stderr);
    free(buf);
}

/* Every failure before the program's own Err path lands here: name the
 * step, report the status, tear down, exit 1. */
static int fail(GeasRuntime* rt, GeasContract* c, const char* what,
                GeasStatus st) {
    fprintf(stderr, "%s: %s (status %d)\n", k_prog, what, (int)st);
    if (c) geas_contract_break(c);
    if (rt) geas_runtime_shutdown(rt);
    return 1;
}

int main(int argc, char** argv) {
    GeasRuntime* rt = NULL;
    GeasStatus st = geas_runtime_init(NULL, &rt);
    if (st != GEAS_OK) return fail(NULL, NULL, "the runtime failed to start", st);
    st = geas_module_register(rt);
    if (st != GEAS_OK) return fail(rt, NULL, "the module failed to register", st);
    geas_runtime_freeze(rt);

    GeasContract* c = NULL;
    st = geas_contract_sign(rt, "Main", NULL, 0, 0, &c);
    if (st != GEAS_OK) return fail(rt, NULL, "the Main contract refused to sign", st);

    /* argv[1..] become Main.run's args. The instance is signed first on
     * purpose: the list and its strings are built through the instance so
     * the frame copy at fulfill reads instance owned bytes alone. */
    GeasValue args;
    uint64_t nargs = argc > 1 ? (uint64_t)(argc - 1) : 0;
    st = geas_list_new(c, GEAS_TY_STRING, nargs, &args);
    if (st != GEAS_OK) return fail(rt, c, "the argument list failed to allocate", st);
    for (int i = 1; i < argc; i++) {
        GeasValue s = geas_string_copy(c, (const uint8_t*)argv[i], strlen(argv[i]));
        st = geas_list_push(c, &args, &s);
        if (st != GEAS_OK) return fail(rt, c, "an argument failed to copy", st);
    }

    GeasValue out;
    memset(&out, 0, sizeof(out));
    st = geas_pledge_fulfill_sync(c, "run", &args, 1, NULL, 0, &out);
    if (st != GEAS_OK) return fail(rt, c, "Main.run failed to deliver", st);

    int code = 1;
    if (out.ty == GEAS_TY_RESULT && out.tag == 0 && out.as.box) {
        code = (int)(((const GeasValue*)out.as.box)->as.i & 255);
    } else if (out.ty == GEAS_TY_RESULT && out.tag == 1) {
        fprintf(stderr, "%s: Main.run reported ", k_prog);
        if (out.as.box) render_stderr((const GeasValue*)out.as.box);
        else fputs("Err(?)", stderr);
        fputc('\n', stderr);
    } else {
        fprintf(stderr, "%s: Main.run delivered an unexpected shape\n", k_prog);
    }
    geas_contract_break(c);
    geas_runtime_shutdown(rt);
    return code;
}
)WRAP";

// The run pledge Main declares outside any subcontract, the last one when
// the name repeats, null when there is none
const PledgeDecl* findRunPledge(const ContractDecl& contract) {
    const PledgeDecl* run = nullptr;
    for (const Member& member : contract.members) {
        const auto* pledge = std::get_if<PledgeDecl>(&member);
        if (pledge != nullptr && pledge->name == runPledgeName) {
            run = pledge;
        }
    }
    return run;
}

// Holds the run pledge to (List<String>) -> Result<Int, E>, concrete
void checkRunPledge(const EmitLookup& lookup, const PledgeDecl& run) {
    TypeArena& types = lookup.types();
    const CallableSig sig = lookup.pledgeSig(run);
    const TyId wanted = types.list(types.scalar(TyKind::String));
    if (sig.params.size() != 1 || sig.params[0] != wanted) {
        lookup.fault(run.lo, run.hi,
                     "Main.run must take exactly one parameter of type List<String>");
    }
    const TyNode ret = types.node(sig.ret);
    if (ret.kind != TyKind::Result || ret.args[0] != types.scalar(TyKind::Int)) {
        lookup.fault(run.lo, run.hi, "Main.run must return Result<Int, E>");
    }
    if (!run.body) {
        lookup.fault(run.lo, run.hi,
                     "Main.run cannot be abstract: a standalone program has no host to bind it");
    }
}

}  // namespace

std::vector<Diagnostic> checkMainContract(CheckedProgram& checked) {
    std::vector<Diagnostic> faults;
    const EmitLookup lookup{checked, faults};
    const GlobalEntry* global = lookup.resolved().global(mainContractName);
    const ContractDecl* contract = global == nullptr || global->kind != GlobalKind::Contract
                                       ? nullptr
                                       : contractAt(lookup.ast(), global->declIndex);
    if (contract == nullptr) {
        lookup.fault(0, 0, "a --bin build needs exactly one Main contract");
        return faults;
    }
    if (contract->isInternal) {
        lookup.fault(contract->lo, contract->hi,
                     "the Main contract cannot be internal: the entry wrapper signs it by name");
        return faults;
    }
    // The entry wrapper fulfills run itself, which an engine driven contract
    // refuses, since its course runs its pledges
    const bool hasCourse = std::any_of(contract->members.begin(), contract->members.end(),
        [](const Member& member) { return std::holds_alternative<CourseDecl>(member); });
    if (hasCourse) {
        lookup.fault(contract->lo, contract->hi,
                     "the Main contract cannot carry a course: the entry wrapper fulfills run itself");
        return faults;
    }
    const PledgeDecl* run = findRunPledge(*contract);
    if (run == nullptr) {
        lookup.fault(contract->lo, contract->hi,
                     "the Main contract must declare a run pledge outside any subcontract");
        return faults;
    }
    checkRunPledge(lookup, *run);
    return faults;
}

std::string emitMainWrapper(std::string_view stem) {
    return fillTemplate(wrapperTemplate, {{"@STEM@", stem}});
}

}  // namespace geas
